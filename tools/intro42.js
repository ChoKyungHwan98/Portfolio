const puppeteer=require('puppeteer-core');
(async()=>{const [,,W,H,out]=process.argv;
const b=await puppeteer.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox','--hide-scrollbars']});
const p=await b.newPage(); const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
await p.setViewport({width:+W,height:+H});
const c=await p.target().createCDPSession(); const frames=[];
await c.send('Page.startScreencast',{format:'png',everyNthFrame:1});
c.on('Page.screencastFrame',async f=>{frames.push({t:f.metadata.timestamp,d:f.data}); await c.send('Page.screencastFrameAck',{sessionId:f.sessionId}).catch(()=>{});});
const t0=Date.now()/1000; await p.goto('http://localhost:8766/index.html',{waitUntil:'domcontentloaded'});
await new Promise(r=>setTimeout(r,2200)); await c.send('Page.stopScreencast');
const fs=require('fs'); fs.mkdirSync(out,{recursive:true});
const st=frames[0].t; const want=[0.05,0.25,0.45,0.65,0.85,1.0,1.2,1.6];
want.forEach((w,i)=>{let best=frames[0];for(const f of frames) if(Math.abs(f.t-st-w)<Math.abs(best.t-st-w)) best=f; fs.writeFileSync(`${out}/i${i}_${(best.t-st).toFixed(2)}.png`,Buffer.from(best.d,'base64'));});
console.log(frames.length,'frames', errs.length?errs:'no errors'); await b.close();})();
